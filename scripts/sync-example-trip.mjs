// Turns the backend's recorded example trip (B9) into a typed fixture, so
// `tsc` fails if our types drift from what the API really sends.
// Usage: npm run sync:example-trip [-- <path to example-trip-response.json>]
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const source = resolve(process.argv[2] ?? "../backend/docs/example-trip-response.json");
const target = resolve("src/features/trip-planner/fixtures/example-trip.ts");
const trip = JSON.parse(readFileSync(source, "utf8"));

writeFileSync(
  target,
  `// Generated by scripts/sync-example-trip.mjs from weather-truck-backend's
// docs/example-trip-response.json (a real Chicago → Denver trip). Don't edit by hand.
import type { Trip } from "../types";

export const exampleTrip = ${JSON.stringify(trip)} satisfies Trip;
`,
);
console.log(`Wrote ${target} from ${source}`);
